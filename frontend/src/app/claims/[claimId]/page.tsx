"use client";

import { useCallback, useEffect, useState } from "react";
import Link from "next/link";
import { useParams } from "next/navigation";

type ClaimDetail = {
  id: number;
  claim_uid: string;
  document_id: number;
  source_block_id: number | null;
  source_page_number: number;
  source_text: string;
  normalized_claim: string;
  claim_type: string;
  entity_name: string | null;
  stock_code: string | null;
  metric: string | null;
  metric_code: string | null;
  reported_value: number | null;
  reported_value_text: string | null;
  value_operator: string;
  unit: string | null;
  currency: string | null;
  period: string | null;
  period_type: string;
  comparison_period: string | null;
  comparison_type: string;
  scope: string | null;
  claim_nature: string;
  risk_level: string;
  risk_reason: string | null;
  requires_calculation: boolean;
  requires_external_evidence: boolean;
  extraction_method: string;
  confidence: number;
  review_status: string;
  review_comment: string | null;
  review_changes: string | null;
};

export default function ClaimDetailPage() {
  const params = useParams<{ claimId: string }>();
  const claimId = params.claimId;

  const [claim, setClaim] = useState<ClaimDetail | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [comment, setComment] = useState("");
  const [msg, setMsg] = useState<string | null>(null);

  const load = useCallback(() => {
    fetch(`/api/v1/claims/${claimId}`)
      .then((r) => (r.ok ? r.json() : Promise.reject(new Error(`HTTP ${r.status}`))))
      .then(setClaim)
      .catch((e: Error) => setError(e.message));
  }, [claimId]);

  useEffect(() => {
    load();
  }, [load]);

  async function review(status: string) {
    setMsg(null);
    try {
      const resp = await fetch(`/api/v1/claims/${claimId}/review`, {
        method: "PATCH",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ review_status: status, comment: comment || null }),
      });
      const body = await resp.json();
      if (!resp.ok) {
        throw new Error(body?.error ? `${body.error.code}: ${body.error.message}` : `HTTP ${resp.status}`);
      }
      setMsg(`已更新审核状态：${status}`);
      setClaim(body);
    } catch (e) {
      setMsg(e instanceof Error ? `失败：${e.message}` : String(e));
    }
  }

  const fields: Array<[string, string | number | boolean | null]> = claim
    ? [
        ["claim_uid", claim.claim_uid],
        ["主张类型", claim.claim_type],
        ["主体", claim.entity_name],
        ["股票代码", claim.stock_code],
        ["指标", claim.metric],
        ["指标代码", claim.metric_code],
        ["数值", `${claim.reported_value ?? "—"}${claim.unit ? ` ${claim.unit}` : ""}（原文：${claim.reported_value_text ?? "—"}）`],
        ["数值运算符", claim.value_operator],
        ["币种", claim.currency],
        ["期间", `${claim.period ?? "—"}（${claim.period_type}）`],
        ["比较期间", `${claim.comparison_period ?? "—"}（${claim.comparison_type}）`],
        ["口径", claim.scope],
        ["主张性质", claim.claim_nature],
        ["风险等级", `${claim.risk_level}（${claim.risk_reason ?? ""}）`],
        ["需计算", claim.requires_calculation ? "是" : "否"],
        ["需外部证据", claim.requires_external_evidence ? "是" : "否"],
        ["提取方式", claim.extraction_method],
        ["置信度", claim.confidence],
        ["审核状态", claim.review_status],
      ]
    : [];

  return (
    <main>
      <h1>主张详情</h1>
      <p className="mock-badge">Mock extraction — not generated by a real language model</p>
      {error && <p className="bad">加载失败：{error}</p>}
      {!claim && !error && <p className="pending">加载中…</p>}

      {claim && (
        <>
          <section className="card">
            <h2>原始报告上下文</h2>
            <blockquote className="source-quote">{claim.source_text}</blockquote>
            <p className="muted">
              来源定位：document_id={claim.document_id} ｜ source_block_id={claim.source_block_id ?? "—"}
              ｜ 页码 page_number={claim.source_page_number}
            </p>
          </section>

          <section className="card">
            <h2>系统结构化结果</h2>
            <table>
              <tbody>
                {fields.map(([k, v]) => (
                  <tr key={k}>
                    <th className="field-key">{k}</th>
                    <td>{String(v ?? "—")}</td>
                  </tr>
                ))}
              </tbody>
            </table>
            {claim.review_changes && (
              <p className="muted">人工修改记录（原始输出保留）：{claim.review_changes}</p>
            )}
          </section>

          <section className="card">
            <h2>人工审核</h2>
            <div className="form-row">
              <input
                value={comment}
                onChange={(e) => setComment(e.target.value)}
                placeholder="审核意见（可选）"
              />
            </div>
            <div className="form-row">
              <button onClick={() => review("APPROVED")}>通过</button>
              <button onClick={() => review("REJECTED")}>驳回</button>
              <button onClick={() => review("PENDING")}>重置待定</button>
              <button onClick={() => review("EDITED")}>标记已编辑</button>
            </div>
            {msg && <p className={msg.startsWith("失败") ? "bad" : "good"}>{msg}</p>}
          </section>
        </>
      )}

      <p>
        <Link href={claim ? `/documents/${claim.document_id}/claims` : "/documents"}>
          ← 返回主张列表
        </Link>
      </p>
    </main>
  );
}
