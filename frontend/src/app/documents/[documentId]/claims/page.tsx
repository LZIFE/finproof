"use client";

import { useEffect, useState } from "react";
import Link from "next/link";
import { useParams } from "next/navigation";

type ClaimRow = {
  id: number;
  claim_uid: string;
  source_text: string;
  normalized_claim: string;
  claim_type: string;
  metric_code: string | null;
  reported_value: number | null;
  unit: string | null;
  period: string | null;
  risk_level: string;
  claim_nature: string;
  requires_calculation: boolean;
  confidence: number;
  review_status: string;
};

export default function ClaimsListPage() {
  const params = useParams<{ documentId: string }>();
  const documentId = params.documentId;

  const [claims, setClaims] = useState<ClaimRow[]>([]);
  const [total, setTotal] = useState(0);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    fetch(`/api/v1/documents/${documentId}/claims?page=1&page_size=100`)
      .then((r) => (r.ok ? r.json() : Promise.reject(new Error(`HTTP ${r.status}`))))
      .then((data: { total: number; claims: ClaimRow[] }) => {
        setTotal(data.total);
        setClaims(data.claims);
      })
      .catch((e: Error) => setError(e.message));
  }, [documentId]);

  return (
    <main>
      <h1>主张列表</h1>
      <p className="mock-badge">Mock extraction — not generated by a real language model</p>
      <p className="desc">文档 {documentId} ｜ 共 {total} 条主张</p>
      {error && <p className="bad">加载失败：{error}</p>}
      <section className="card">
        <table>
          <thead>
            <tr>
              <th>原始句子</th>
              <th>规范化主张</th>
              <th>类型</th>
              <th>指标</th>
              <th>数值</th>
              <th>期间</th>
              <th>风险</th>
              <th>性质</th>
              <th>需计算</th>
              <th>置信度</th>
              <th>审核</th>
            </tr>
          </thead>
          <tbody>
            {claims.map((c) => (
              <tr key={c.id}>
                <td className="block-text">{c.source_text}</td>
                <td className="block-text">{c.normalized_claim}</td>
                <td>{c.claim_type}</td>
                <td>{c.metric_code ?? "—"}</td>
                <td>
                  {c.reported_value ?? "—"}
                  {c.unit ? ` ${c.unit}` : ""}
                </td>
                <td>{c.period ?? "—"}</td>
                <td>{c.risk_level}</td>
                <td>{c.claim_nature}</td>
                <td>{c.requires_calculation ? "是" : "否"}</td>
                <td>{c.confidence}</td>
                <td>
                  {c.review_status}{" "}
                  <Link href={`/claims/${c.id}`}>详情</Link>
                </td>
              </tr>
            ))}
          </tbody>
        </table>
      </section>
      <p>
        <Link href={`/documents/${documentId}`}>← 返回文档查看</Link>
      </p>
    </main>
  );
}
